    /**
     * Use Arc to draw an elliptically curved line with the current Pen.
     *
     * @param x1 int
     * @param y1 int
     * @param x2 int
     * @param y2 int
     * @param startAngle double
     * @param sweepAngle double
     */
    public void arc(int x1, int y1, int x2, int y2, double startAngle,
                    double sweepAngle) {
        if (getPen().getVisible()) {
            int sangle = 90 + Utils.round(startAngle);
            int eangle = sangle + Utils.round(sweepAngle);
            int w = x2 - x1;
            int h = y2 - y1;

            m_String = "<v:arc style=\"position:absolute;left:" +
                       Integer.toString(x1) +
                       ";top:" + Integer.toString(y1);
            m_String += ";width:" + Integer.toString(w) + ";height:" +
                    Integer.toString(h) +
                    "\"";
            m_String += " startangle=\"" + Integer.toString(sangle) +
                    "\" endangle=\"" +
                    Integer.toString(eangle) + "\"";

            m_String += " filled=\"f\"";

            if (getPen().getVisible()) {
                m_String += " strokecolor=" + vmlColor(getPen().getColor(), false);
            } else {
                m_String += " stroked=\"f\"";
            }
            m_String += ">";
            addToStream(m_String);
        }
    }

