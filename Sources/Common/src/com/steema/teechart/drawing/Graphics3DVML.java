    private String fontProperties(ChartFont f) {
        m_String = "font-family:" + f.getName().toString() + "; font-size:" +
                   Integer.toString(f.getSize()) + "pt; ";
        if (f.getBold()) {
            m_String += " font-weight=bold;";
        }
        if (f.getItalic()) {
            m_String += " font-style=italic;";
        }
        if (f.getUnderline()) {
            m_String += " text-decoration=underline;";
        }
        if (f.getStrikeout()) {
            m_String += " text-decoration=line-through;";
        }
        return m_String;
    }

    private void doText(ChartFont f, int x, int y, double degAngle, String text,
                        Color c) {
        float tw = 0.0F;
        if (getTextAlign() == StringAlignment.CENTER) {
            tw = textWidth(text) * 0.5F;
        } else if (getTextAlign() == StringAlignment.FAR) {
            tw = textWidth(text);
        }
        x -= Utils.round(tw);
        m_String = "<v:textbox style=\"position:absolute; left:" +
                   Integer.toString(x) +
                   "; top:" + Integer.toString(y);
        m_String += "; color:" + vmlColor(c, true) + "; text-align:left; ";
        m_String += fontProperties(f) + "\">";
        m_String += text;
        m_String += "</v:textbox>";
        addToStream(m_String);
    }

    private void internalPolygon(ChartBrush br, ChartPen pn, boolean polyLine,
                                 Point[] p) {
        if (br.getVisible() || pn.getVisible()) {
            prepareShape();
            m_String = "<v:path v=\"m " + pointToStr(p[0].x, p[0].y) + " l ";
            for (int i = 1; i <= p.length; i++) {
                m_String += pointToStr(p[i].x, p[i].y) + " ";
            }
            if (polyLine) {
                m_String += " e\"/>";
            } else {
                m_String += " x e\"/>";
            }
            addToStream(m_String);
            addToStream("</v:shape>");
        }
    }

