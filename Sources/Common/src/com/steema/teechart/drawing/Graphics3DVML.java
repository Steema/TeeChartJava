    private String pointToStr(int x, int y) {
        m_String = Integer.toString(x) + "," + Integer.toString(y);
        return m_String;
    }

    static private String penStyle(ChartPen ipen) {
        if (ipen.getStyle() == DashStyle.SOLID) {
            return "";
        } else {
            return ipen.getStyle().toString();
        }
    }

    private String penWidth(ChartPen ipen,
                            String element) {
        if (ipen.getWidth() > 1) {
            m_String = " " + element + "=\"" + Integer.toString(ipen.getWidth()) +
                       "\"";
        } else {
            m_String = "";
        }
        return m_String;
    }

    private String vmlPen(String element) {
        m_String = "\" strokecolor=" + vmlColor(getPen().getColor(), false);
        if (getPen().getStyle() != DashStyle.SOLID) {
            m_String += "><v:stroke dashstyle=\"" + penStyle(getPen()) + "\"" +
                    penWidth(getPen(), "weight") + "/></v:" + element + ">";
        } else {
            m_String += penWidth(getPen(), "strokeweight") + "/>";
        }
        return m_String;
    }

    private String vmlColor(Color c, boolean inter) {
        if (inter) {
            m_String = "";
        } else {
            m_String = "\"";
        }

        // one of pre-defined html colors
        if (c == Color.BLACK) {
            m_String += "black";
        } else if (c == Color.SILVER) {
            m_String += "silver";
        } else if (c == Color.GRAY) {
            m_String += "gray";
        } else if (c == Color.WHITE) {
            m_String += "white";
        } else if (c == Color.MAROON) {
            m_String += "maroon";
        } else if (c == Color.RED) {
            m_String += "red";
        } else if (c == Color.PURPLE) {
            m_String += "purple";
        } else if (c == Color.FUCHSIA) {
            m_String += "fuchsia";
        } else if (c == Color.GREEN) {
            m_String += "green";
        } else if (c == Color.LIME) {
            m_String += "lime";
        } else if (c == Color.OLIVE) {
            m_String += "olive";
        } else if (c == Color.YELLOW) {
            m_String += "yellow";
        } else if (c == Color.NAVY) {
            m_String += "navy";
        } else if (c == Color.BLUE) {
            m_String += "blue";
        } else if (c == Color.TEAL) {
            m_String += "teal";
        } else if (c == Color.AQUA) {
            m_String += "aqua";
        } else {
            m_String += "#" + Integer.toHexString(c.getRed()); // ("X2");
            m_String += Integer.toHexString(c.getGreen()); // ("X2");
            m_String += Integer.toHexString(c.getBlue()); // ("X2");
        }
        if (!inter) {
            m_String += "\"";
        }
        return m_String;
    }

    private void prepareShape() {
        m_String = "<v:shape style=\"position:absolute;" + theBounds() + "\"";
        if (getBrush().getVisible()) {
            m_String += " fillcolor=" + vmlColor(getBrush().getColor(), false);
        } else {
            m_String += " filled=\"f\"";
        }

        if (getPen().getVisible()) {
            m_String += " strokecolor=" + vmlColor(getPen().getColor(), false);
        } else {
            m_String += " stroked=\"f\"";
        }

        float op = 1.0F - getBrush().getTransparency() * 0.01F;
        if (op < 1.0F) {
            String trfact = Float.toString(op);
            trfact = trfact.replace(',', '.');
            m_String += " opacity=\"" + trfact + "\"";
        }
        m_String += ">";
        addToStream(m_String);
    }

    private void internalRect(ChartBrush b, Rectangle r, boolean usePen,
                              boolean isRound) {
        if (b.getVisible() || (usePen && getPen().getVisible())) {
            m_String = "<v:";
            String telement = "rect";
            if (isRound) {
                telement = "roundrect";
            }

            m_String += telement;
            m_String += " style=\"position:absolute;left:";
            m_String += Integer.toString(r.getLeft()) + ";top:" +
                    Integer.toString(r.getTop()) +
                    ";width:";
            int modwh = r.width - 1;
            m_String += Integer.toString(modwh) + ";height:";
            modwh = r.height - 1;
            m_String += Integer.toString(modwh) + "\"";

            if (b.getVisible()) {
                m_String += " fillcolor=" + vmlColor(b.getColor(), false);
            } else {
                m_String += " filled=\"false\"";
            }

            if (usePen && getPen().getVisible()) {
                m_String += " strokecolor=" + vmlColor(getPen().getColor(), false);
            } else {
                m_String += " stroked=\"f\"";
            }

            float op = 1.0F - b.getTransparency() * 0.01F;
            if (op < 1.0F) {
                String trfact = Float.toString(op);
                trfact = trfact.replace(',', '.');
                m_String += " opacity=\"" + trfact + "\"";
            }

            m_String += vmlPen(telement);
            addToStream(m_String);
        }
    }

