    /**
     * Fills a screen area with color-gradient background.
     *
     *
     * @param left int
     * @param top int
     * @param right int
     * @param bottom int
     * @param startColor Color
     * @param endColor Color
     * @param direction GradientDirection
     */
    public void gradientFill(int left, int top, int right, int bottom,
                             Color startColor, Color endColor,
                             GradientDirection
                             direction) {

        int theAngle;
        if (direction == GradientDirection.VERTICAL) {
            theAngle = 180;
        } else if (direction ==
                   GradientDirection.HORIZONTAL) {
            theAngle = 90;
        } else if (direction ==
                   GradientDirection.FORWARDDIAGONAL) {
            theAngle = 45;
        } else {
            theAngle = 315;
        }

        m_String = "<v:shape style=\"position:absolute;" + theBounds() +
                   ";\" stroked=\"f\">\n";
        m_String += " <v:path v=\"M " + pointToStr(left, top) + " L ";
        m_String += pointToStr(right, top) + " " + pointToStr(right, bottom) +
                " ";
        m_String += pointToStr(left, bottom) + " X E\"/>\n";

        m_String += " <v:fill type=\"gradient\" color=" + vmlColor(startColor, false) +
                " color2=" + vmlColor(endColor, false) + "\n";
        // missing transparency part

        if (getBrush().getGradient().getTransparency() != 0) {
            double tr = (100 - getBrush().getGradient().getTransparency()) *
                        0.01;
            m_String += " opacity=\"" + Double.toString(tr) + "\"";
        }

        m_String += " method=\"sigma\" angle=\"" + Integer.toString(theAngle) +
                "\" focus=\"100%\"/>\n";
        m_String += "</v:shape>";
        addToStream(m_String);

    }

