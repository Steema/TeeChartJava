package com.steema.teechart.misc;

/**
 *
 * @author Administrator
 */
public class MultiVar
{

  public double varA;
  public double varB;
  public double varC;
  public double varD;

  public MultiVar(double a, double b)
  {
    varA = a;
    varB = b;
  }

  public MultiVar(double a, double b, double c, double d)
  {
    varA = a;
    varB = b;
    varC = c;
    varD = d;
  }

}
