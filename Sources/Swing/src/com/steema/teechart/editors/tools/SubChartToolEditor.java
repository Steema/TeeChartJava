    public void setTool(Tool t) {
       this.tool = (SubChartTool)t; 
       lbCharts.setModel(new DefaultListModel());
       lbCharts.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
       DefaultListModel l = (DefaultListModel) lbCharts.getModel();
       l.clear();
       
       if(tool != null) {
           for(int i = 0; i < tool.getCharts().size(); i++) {
               if(tool.getCharts().get(i).getChart().getName() == null || 
                       tool.getCharts().get(i).getChart().getName().equals("")) {
                   l.addElement("Chart" + String.valueOf(i + 1));
               }
               else {
                   l.addElement(tool.getCharts().get(i).getChart().getName());
               }
           }
           
           if(lbCharts.getModel().getSize() > 0) {
               lbCharts.setSelectedIndex(0);
           }
           
           lbChartsValueChanged(null);
       }
        
    }

    private void enableButtons() {
        tabControl.setEnabled(lbCharts.getModel().getSize() > 0);
        udLeft.setEnabled(tabControl.isEnabled());
        udTop.setEnabled(tabControl.isEnabled());
        udHeight.setEnabled(tabControl.isEnabled());
        udWidth.setEnabled(tabControl.isEnabled());
        
        lWidth.setEnabled(tabControl.isEnabled());
        lTop.setEnabled(tabControl.isEnabled());
        lLeft.setEnabled(tabControl.isEnabled());
        lHeight.setEnabled(tabControl.isEnabled());
        
        bUp.setEnabled(tabControl.isEnabled());
        bDown.setEnabled(tabControl.isEnabled());
        bDelete.setEnabled(tabControl.isEnabled());
        bRename.setEnabled(tabControl.isEnabled());
    }
    
    private String currentChartName() {
        String result = currentChart().getChart().getName();
        if(result == null || result.equals("")) {
           result = "Chart" + (lbCharts.getSelectedIndex() + 1); 
        }
        return result;
    }
    
    private SubChart currentChart() {
        return tool.getCharts().get(lbCharts.getSelectedIndex());
    }

    private void swapChart(int a, int b) {
        SubChart chartA = tool.getCharts().get(a);
        SubChart chartB = tool.getCharts().get(b);
        
        tool.getCharts().set(a, chartB);
        tool.getCharts().set(b, chartA);
        
        DefaultListModel l = (DefaultListModel) lbCharts.getModel();
        l.setElementAt(chartB, a);
        l.setElementAt(chartA, b);
    }
